    private void BTNSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNSalvarActionPerformed
        
        String nome = TXTFNome.getText().trim();
        String idade = TXTFIdade.getText().trim();
        String email = TXTFEmail.getText().trim();
        
        if (nome.isEmpty()  || idade.isEmpty() || email.isEmpty() ) {
            
            JOptionPane.showMessageDialog(this, "Preencha todos os campos");
            return;
        }
        
        File arquivo = new File("cadastro.txt");
        
        try {
            String mensagem;
            
            if(arquivo.exists()) {
                mensagem = "Arquvio ja existe. Cadastro salvo";
            }
            else {
                arquivo.createNewFile();
                mensagem = "Arquivo criado e cadastro salvo!!";
            }
            
            try (FileWriter cadastroSalvo = new FileWriter(arquivo, true)) {
                cadastroSalvo.write(nome + ";" + idade + ";" + email +  System.lineSeparator());
            }
            JOptionPane.showMessageDialog(this, mensagem);
            
            TXTFNome.setText("");
            TXTFIdade.setText("");
            TXTFEmail.setText("");
        }
        catch (IOException e ) {
            
            JOptionPane.showMessageDialog(this, "Erro ao salvar: " + e.getMessage());
        }
    }//GEN-LAST:event_BTNSalvarActionPerformed

    private void BTNListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNListarActionPerformed
        
        File arquivo = new File("cadastro.txt");
        
        if (!arquivo.exists()) {
            
            JOptionPane.showMessageDialog(this, "Nenhum dado salvo ainda!!!!!!!!!");
            return;
        }
        
        DefaultTableModel modelo = new DefaultTableModel(new Object[] {"nome", "idade", "email"}, 0);
        
        try (Scanner leitor = new Scanner(arquivo)) {
            while (leitor.hasNextLine()) {
                
                String linha = leitor.nextLine();
                String[] campos = linha.split(";");
                
                if(campos.length == 3) {
                    modelo.addRow(campos);
                }
            }
            
            tblCadastro.setModel(modelo);
        }
        
        catch(FileNotFoundException e) {
            
            JOptionPane.showMessageDialog(this, "Erro na leitura do arquivo " + e.getMessage());
        }
    }//GEN-LAST:event_BTNListarActionPerformed

