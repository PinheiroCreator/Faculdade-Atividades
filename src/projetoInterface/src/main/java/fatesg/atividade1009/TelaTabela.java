    private void BntCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BntCadastrarActionPerformed
        // TODO add your handling code here:
        String codigo = TxTCodigo.getText();
        String nomeProduto = TxTProduto.getText();
        String valor = TxTValor.getText();
        
        DefaultTableModel  tabelaProdutos = (DefaultTableModel) TBLProdutos.getModel();
        
        Object[] tbtProdutos = new Object[] {
            
            codigo,
            nomeProduto,
            valor
        };
        
        tabelaProdutos.addRow(tbtProdutos);
        
        TxTCodigo.setText("");
        TxTProduto.setText("");
        TxTValor.setText("");
        
    }//GEN-LAST:event_BntCadastrarActionPerformed

    private void BNTExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BNTExcluirActionPerformed
        // TODO add your handling code here:
        
        int linhaSelecionada = TBLProdutos.getSelectedRow();
        
        if(linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Por gentileza, selecione uma linha");
        }
        else {
           DefaultTableModel  tabelaProdutos = (DefaultTableModel) TBLProdutos.getModel();
           tabelaProdutos.removeRow(linhaSelecionada);
           JOptionPane.showMessageDialog(this, "Produto excluido");
        }
    }//GEN-LAST:event_BNTExcluirActionPerformed

