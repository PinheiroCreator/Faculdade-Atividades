        public void limparTXTF() {

            TXTFNome.setText("");
            TXTFTelefone.setText("");
            TXTFEmail.setText("");
        }


    private void BTNSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNSalvarActionPerformed

        String nome = TXTFNome.getText().trim();
        String telefone = TXTFTelefone.getText().trim();
        String email = TXTFEmail.getText().trim();

        if (nome.isEmpty() || telefone.isEmpty() || email.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Preencha todos os campos !!!!!!!!!!!!!!");
            return;
        } else if (!email.contains("@")) {

            JOptionPane.showMessageDialog(this, "EMAIL INVALIDO ");
            return;
        } else {

            int numero;

            try {
                numero = Integer.parseInt(telefone);
            } catch (NumberFormatException e) {

                JOptionPane.showMessageDialog(this, "Digite um numero valido !!!");
                TXTFTelefone.setText(null);
                return;
            }

            File arquivo = new File("Agenda.txt");

            try {

                if (!arquivo.exists()) {

                    arquivo.createNewFile();
                    JOptionPane.showMessageDialog(this, "Arquivo criado e Salvo!!!!!");
                    limparTXTF();

                } else {
                    try (FileWriter Contato = new FileWriter(arquivo, true)) {

                        Contato.write(nome + ";" + telefone + ";" + email + System.lineSeparator());
                        JOptionPane.showMessageDialog(this, "Contato SALVO!!!!!");
                        limparTXTF();
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "ERRO!!!!");
            }
        }


    }//GEN-LAST:event_BTNSalvarActionPerformed

    private void BTNListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNListarActionPerformed

        File arquivo = new File("Agenda.txt");

        if (!arquivo.exists()) {

            TXTAContatos.setText("");
            JOptionPane.showMessageDialog(this, "Nao existe Contatos para listar!!!!!!!!");
            return;
        } else {

            try (BufferedReader leitor = new BufferedReader(new FileReader("Agenda.txt"))) {

                String linha;
               
                while ((linha = leitor.readLine()) != null) {

                    String[] partes = linha.split(";");
                    
                    TXTAContatos.append(
                            "Nome:: " + partes[0] + "\n"
                            + "Telefone: " + partes[1] + "\n"
                            + "Email:  " + partes[2] + "\n"
                            + "||-----------------------------------------------------------------|| \n"
                            
                    );
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Erro ao ler o arquivo.");
                e.printStackTrace();
            }
    }//GEN-LAST:event_BTNListarActionPerformed
        }
