    private void BTNNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNNovoActionPerformed

        if (!TXTABlocoDeNotas.getText().trim().isEmpty()) {
            int resp = JOptionPane.showConfirmDialog(this,
                    "Descartar o texto atual?",
                    "Novo", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (resp != JOptionPane.YES_OPTION) {
                return;
            }
        }
        TXTFNomeArquivo.setText("");
        TXTABlocoDeNotas.setText("");


    }//GEN-LAST:event_BTNNovoActionPerformed

    private void BTNSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNSalvarActionPerformed

        String nomeArquivo = TXTFNomeArquivo.getText().trim();
        String texto = TXTABlocoDeNotas.getText();

        if (nomeArquivo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira o nome do arquivo!");
            return;
        }

        File arquivo = new File(nomeArquivo);

        if (arquivo.exists()) {

            int resp = JOptionPane.showConfirmDialog(this,
                    "O arquivo já existe. Deseja sobrescrever?",
                    "Confirmação", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

            if (resp != JOptionPane.YES_OPTION) {

                return;
            }
        }

        try (FileWriter escrever = new FileWriter(arquivo, false)) {

            escrever.write(texto);

            JOptionPane.showMessageDialog(this, "Arquivo " + nomeArquivo + " salvo!");

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "ERRO AO SALVAR");
        }
    }//GEN-LAST:event_BTNSalvarActionPerformed

    private void BTNAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNAbrirActionPerformed

        String nomeArquivo = TXTFNomeArquivo.getText().trim();

        if (nomeArquivo.isEmpty()) {
            
            JOptionPane.showMessageDialog(this, "Insira o nome do arquivo!");
            return;
            
        }

        File arquivo = new File(nomeArquivo);

        if (!arquivo.exists()) {
            
            JOptionPane.showMessageDialog(this, "Arquivo não encontrado!");
            return;
            
        }

        try (BufferedReader leitor = new BufferedReader(new FileReader(arquivo))) {
           
            String conteudo = "";
            
            String linha;

            while ((linha = leitor.readLine()) != null) {
                conteudo += linha + "\n";
            }

            TXTABlocoDeNotas.setText(conteudo);
            
        } 
        
        catch (IOException e) {
            JOptionPane.showMessageDialog(this, "ERRO AO ABRIR");
        }
    }//GEN-LAST:event_BTNAbrirActionPerformed

