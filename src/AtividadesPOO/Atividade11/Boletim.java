    private void BTNListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNListarActionPerformed

        File arquivo = new File("alunos.txt");

        if (!arquivo.exists()) {

            JOptionPane.showMessageDialog(this, "NAO EXISTE NOTAS PARA MOSTRAR ! ");
            return;
        }

        DefaultTableModel modelo = new DefaultTableModel(new Object[]{"nome", "nota1", "nota2", "media", "situacao"}, 0);

        double somaMedias = 0;
        int quantidade = 0;

        try (Scanner leitor = new Scanner(arquivo)) {

            while (leitor.hasNextLine()) {

                String linha = leitor.nextLine();
                String[] campos = linha.split(";");

                if (campos.length == 5) {

                    modelo.addRow(campos);
                    somaMedias += Double.parseDouble(campos[3]);
                    quantidade++;

                }
            }

            TBTNotas.setModel(modelo);

            if (quantidade > 0) {
                jLabel6.setText(String.format("%.2f", somaMedias / quantidade));
            } else {
                jLabel6.setText("0.00");
            }

        } catch (IOException e) {

            JOptionPane.showMessageDialog(this, "Erro na leitura do arquivo " + e.getMessage());
        }
    }//GEN-LAST:event_BTNListarActionPerformed

