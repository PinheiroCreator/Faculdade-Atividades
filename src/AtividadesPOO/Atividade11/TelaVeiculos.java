    private void BTNSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNSalvarActionPerformed

        String placa = TXTPlaca.getText().trim();
        String modelo = TXTFModelo.getText().trim();
        String anoDigitado = TXTFAno.getText().trim();

        if (placa.isEmpty() || modelo.isEmpty() || anoDigitado.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Preencha todos os campos!!!!!!");
            return;
        }

        int ano;

        try {
            ano = Integer.parseInt(anoDigitado);
        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this, "Digite um ano Valido");
            limparTXTF(anoDigitado);
            return;

        }

        if (ano > 2027 || ano < 1700) {

            JOptionPane.showMessageDialog(this, "Digite um ano Valido");
            limparTXTF(anoDigitado);
            return;
        } else {

            veiculo.setPlaca(placa);
            veiculo.setModelo(modelo);
            veiculo.setAno(ano);

            if (!RBTNCarro.isSelected() && !RBTNMoto.isSelected()) {

                JOptionPane.showMessageDialog(this, "ESCOLHA CARRO OU MOTO!!!!");
                return;
            }

            String tipo;

            if (RBTNCarro.isSelected()) {
                tipo = "Carro";
            } else {
                tipo = "Moto";
            }

            try {

                File arquivo = new File("veiculos.txt");

                if (arquivo.createNewFile()) {

                    JOptionPane.showMessageDialog(this, "Arquivo criado e salvo!!");
                    limparTXTF();
                }

                try (BufferedReader ler = new BufferedReader(new FileReader("veiculos.txt"))) {

                    String linha;

                    while ((linha = ler.readLine()) != null) {

                        String[] partes = linha.split(";");

                        if (partes[0].equalsIgnoreCase(placa)) {

                            JOptionPane.showMessageDialog(this, "Essa placa ja existe no sistema!!!");
                            return;
                        }
                    }

                    try (FileWriter VeiculosSalvos = new FileWriter(arquivo, true)) {

                        VeiculosSalvos.write(placa + ";" + modelo + ";" + ano + ";" + tipo + System.lineSeparator());
                        JOptionPane.showMessageDialog(this, "Veiculo Salvo!!!!!");
                        limparTXTF();

                    }
                }
            } catch (IOException e) {

                JOptionPane.showMessageDialog(this, "OCORREU UM ERRO!!!!");
                e.printStackTrace();
                return;
            }
        }

    }//GEN-LAST:event_BTNSalvarActionPerformed

    private void BTNBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNBuscarActionPerformed

        String placa = TXTPlaca.getText().trim();

        if (placa.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Digite a placa para buscar!");
            return;
        }

        File arquivo = new File("veiculos.txt");

        if (!arquivo.exists()) {

            TXTARResultados.setText("");
            JOptionPane.showMessageDialog(this, "Nenhum veículo cadastrado ainda.");
            return;
        }

        try (BufferedReader ler = new BufferedReader(new FileReader("veiculos.txt"))) {

            String linha;
            String tipo;

            while ((linha = ler.readLine()) != null) {
                String[] partes = linha.split(";");

                if (partes.length >= 3 && partes[0].equalsIgnoreCase(placa)) {
                    if (partes.length > 3) {
                        tipo = partes[3];
                    } else {
                        tipo = "Não informado";
                    }

                    TXTARResultados.setText(
                            "Placa: " + partes[0] + "\n"
                            + "Modelo: " + partes[1] + "\n"
                            + "Ano: " + partes[2] + "\n"
                            + "Tipo: " + tipo
                    );
                    return;
                }
            }

            TXTARResultados.setText("");
            JOptionPane.showMessageDialog(this, "Placa não cadastrada.");

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Erro ao ler o arquivo.");
            e.printStackTrace();
        }
    }//GEN-LAST:event_BTNBuscarActionPerformed

