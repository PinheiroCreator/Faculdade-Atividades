    private void limparTela(){
        TXTFId.setText("");
        TXTFNome.setText("");
        TXTFTelefone.setText("");
        TXTFEmail.setText("");
    }
    
    private void BTNIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNIncluirActionPerformed
                try {
            controller.incluir(TXTFNome.getText(), TXTFTelefone.getText(), TXTFEmail.getText());
            this.limparTela();
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(rootPane, erro.getMessage());
        }
            

    }//GEN-LAST:event_BTNIncluirActionPerformed

    private void BTNExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNExcluirActionPerformed
         try {
            controller.excluir(TXTFId.getText());
            this.limparTela();
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(rootPane, erro.getMessage());
        }
    }//GEN-LAST:event_BTNExcluirActionPerformed

    private void BTNAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNAlterarActionPerformed
        
 try {
            controller.alterar(TXTFId.getText(), TXTFNome.getText(),
                    TXTFTelefone.getText(), TXTFEmail.getText());
            JOptionPane.showMessageDialog(rootPane, "Consultor alterado!");
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(rootPane, erro.getMessage());
        }
    }//GEN-LAST:event_BTNAlterarActionPerformed

    private void BTNConsultaeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNConsultaeActionPerformed
      try {
            Consultor pessoa = controller.consultar(TXTFId.getText());
            TXTFId.setText(String.valueOf(pessoa.getId_Consultor()));
            TXTFNome.setText(pessoa.getNome());
            TXTFTelefone.setText(pessoa.getTelefone());
            TXTFEmail.setText(pessoa.getEmail());
        } catch (Exception erro) {
            JOptionPane.showMessageDialog(rootPane, erro.getMessage());
        }
      
       
    }//GEN-LAST:event_BTNConsultaeActionPerformed

